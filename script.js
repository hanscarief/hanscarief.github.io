  function renderGrid() {
    filteredList = SCREENSHOTS_DATA.filter((item) => {
      const matchMod = currentModule === "all" || item.mod === currentModule;
      const q = currentKeyword.trim().toLowerCase();
      const matchSearch =
        !q ||
        item.title.toLowerCase().includes(q) ||
        item.titleEn.toLowerCase().includes(q) ||
        item.desc.toLowerCase().includes(q) ||
        item.descEn.toLowerCase().includes(q) ||
        item.file.toLowerCase().includes(q);
      return matchMod && matchSearch;
    });

    updateCountBar(filteredList.length);
    const zoomLabel = translations[lang].zoom_hint;

    grid.innerHTML = filteredList
      .map((item, idx) => {
        const displayTitle = lang === "en" ? item.titleEn : item.title;
        const displayDesc = lang === "en" ? item.descEn : item.desc;
        const displayMod = lang === "en" ? item.modLabelEn : item.modLabel;
        return `
        <article class="ss-card" data-idx="${idx}" tabindex="0" role="button" aria-label="${displayTitle}">
          <div class="ss-thumb">
            <img src="assets/screenshots/${encodeURIComponent(item.file)}" alt="${displayTitle}" loading="lazy" />
            <span class="ss-num-tag">#${String(item.num).padStart(2, "0")}</span>
            <span class="ss-zoom-hint">${zoomLabel}</span>
          </div>
          <div class="ss-body">
            <span class="ss-mod-tag">${displayMod}</span>
            <h4>${displayTitle}</h4>
            <p>${displayDesc}</p>
            <code class="ss-file">${item.file}</code>
          </div>
        </article>
      `;
      })
      .join("");

    document.querySelectorAll(".ss-card").forEach((card) => {
      card.addEventListener("click", () => {
        const idx = Number(card.dataset.idx);
        openLightbox(idx);
      });
      card.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          const idx = Number(card.dataset.idx);
          openLightbox(idx);
        }
      });
    });
  }

