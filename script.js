// Pastikan pita marquee selalu berjalan mulus meski pengaturan animasi OS dimatikan
  const marqueeWrap = document.querySelector(".marquee-wrap");
  const marqueeTrack = document.querySelector(".marquee-track");
  if (marqueeWrap && marqueeTrack) {
    const computedAnim = window.getComputedStyle(marqueeTrack).animationName;
    const computedDur = parseFloat(window.getComputedStyle(marqueeTrack).animationDuration || "0");
    if (computedAnim === "none" || computedDur <= 0.1) {
      marqueeTrack.style.animation = "none";
      let offset = 0;
      let paused = false;
      marqueeWrap.addEventListener("mouseenter", () => { paused = true; });
      marqueeWrap.addEventListener("mouseleave", () => { paused = false; });
      function stepMarquee() {
        if (!paused) {
          offset += 0.75;
          const halfWidth = marqueeTrack.scrollWidth / 2;
          if (halfWidth > 0 && offset >= halfWidth) {
            offset = 0;
          }
          marqueeTrack.style.transform = `translateX(-${offset}px)`;
        }
        requestAnimationFrame(stepMarquee);
      }
      requestAnimationFrame(stepMarquee);
    }
  }
